// POST /api/detect { text } → { score, reasons, model }   LLM-judged AI probability (0-100).
// Same env as /api/humanize. Used to second-opinion the local statistical detector.
export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  if (req.method === 'OPTIONS') return res.status(204).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });
  const key = process.env.LLM_API_KEY;
  if (!key) return res.status(503).json({ error: 'LLM_API_KEY not configured' });
  let body = req.body; if (typeof body === 'string') { try { body = JSON.parse(body); } catch { body = {}; } }
  const text = (body?.text || '').toString().trim().slice(0, 12000);
  if (!text) return res.status(400).json({ error: 'text required' });
  const base = (process.env.LLM_BASE_URL || 'https://api.groq.com/openai/v1').replace(/\/$/, '');
  const model = process.env.LLM_MODEL || 'llama-3.3-70b-versatile';
  const sys = `You are an AI-text detector. Estimate the probability (0-100) that the text was generated by a language model rather than written by a person.
Judge on: uniform sentence length and rhythm, stock transitions (however/furthermore/moreover/additionally), LLM vocabulary (delve, leverage, foster, crucial, tapestry, landscape, robust, seamless), lists of three, absence of contractions, lack of specific details or personal voice, over-balanced hedging, generic conclusions. Human writing has uneven rhythm, specifics, quirks, fragments, contractions, opinions.
Reply with JSON only: {"score": <int 0-100>, "reasons": ["...", "..."]}`;
  try {
    const r = await fetch(`${base}/chat/completions`, {
      method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${key}` },
      body: JSON.stringify({ model, temperature: 0, response_format: { type: 'json_object' }, messages: [{ role: 'system', content: sys }, { role: 'user', content: text }] }),
    });
    const d = await r.json();
    if (!r.ok) return res.status(502).json({ error: d.error?.message || 'upstream error' });
    let j = {}; try { j = JSON.parse(d.choices?.[0]?.message?.content || '{}'); } catch { }
    const score = Math.max(0, Math.min(100, Math.round(Number(j.score) || 0)));
    res.status(200).json({ score, reasons: Array.isArray(j.reasons) ? j.reasons.slice(0, 4) : [], model });
  } catch (e) { res.status(500).json({ error: e.message }); }
}
